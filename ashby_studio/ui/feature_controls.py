"""Feature-search controls embedded in the existing Local AI Model window."""
from qtpy.QtCore import Signal
from qtpy.QtWidgets import (
    QWidget, QVBoxLayout, QFormLayout, QComboBox, QPushButton, QLabel,
    QDoubleSpinBox, QSpinBox, QProgressBar, QCheckBox,
)


class FeatureControls(QWidget):
    runRequested = Signal()
    cancelRequested = Signal()
    saveRequested = Signal()
    thresholdChanged = Signal(float)
    overlayChanged = Signal()
    runSelected = Signal(str)

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setObjectName("ashby_feature_controls")
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        form = QFormLayout()
        form.setRowWrapPolicy(QFormLayout.WrapLongRows)
        self.scope = QComboBox()
        self.scope.addItem("Loaded image", "image")
        self.scope.addItem("Selected polygon ROI", "roi")
        form.addRow("Search", self.scope)
        self.device = QComboBox()
        self.device.addItem("CPU", "cpu")
        self.device.addItem("Auto (GPU if available)", "auto")
        form.addRow("Device", self.device)
        self.size = QSpinBox()
        self.size.setRange(64, 2048)
        self.size.setValue(672)
        self.size.setSuffix(" px")
        self.stride = QSpinBox()
        self.stride.setRange(32, 2048)
        self.stride.setValue(336)
        self.stride.setSuffix(" px")
        form.addRow("Patch size", self.size)
        form.addRow("Patch stride", self.stride)
        layout.addLayout(form)
        self.find = QPushButton("Find feature")
        self.find.clicked.connect(self.runRequested)
        layout.addWidget(self.find)
        self.cancel = QPushButton("Cancel search")
        self.cancel.clicked.connect(self.cancelRequested)
        self.cancel.setEnabled(False)
        layout.addWidget(self.cancel)
        self.progress = QProgressBar()
        self.progress.setValue(0)
        layout.addWidget(self.progress)
        self.runs = QComboBox()
        self.runs.setSizeAdjustPolicy(QComboBox.AdjustToMinimumContentsLengthWithIcon)
        self.runs.setMinimumContentsLength(12)
        self.runs.setToolTip("Completed searches retained in this case")
        self.runs.currentIndexChanged.connect(lambda _: self.runSelected.emit(self.runs.currentData() or ""))
        layout.addWidget(self.runs)
        threshold_label = QLabel("Minimum displayed score (uncalibrated logit)")
        threshold_label.setWordWrap(True)
        layout.addWidget(threshold_label)
        self.threshold = QDoubleSpinBox()
        self.threshold.setRange(-1_000_000, 1_000_000)
        self.threshold.setDecimals(3)
        self.threshold.setSingleStep(0.1)
        self.threshold.setValue(0)
        self.threshold.setToolTip("Visibility filter only. Zero is an evaluation reference, not diagnostic truth.")
        self.threshold.valueChanged.connect(self.thresholdChanged)
        layout.addWidget(self.threshold)
        self.boxes = QCheckBox("Show candidate patch boxes")
        self.boxes.setChecked(True)
        self.heatmap = QCheckBox("Show patch-score heatmap")
        for box in (self.boxes, self.heatmap):
            box.toggled.connect(self.overlayChanged)
            layout.addWidget(box)
        self.summary = QLabel("No feature search results.")
        self.summary.setWordWrap(True)
        layout.addWidget(self.summary)
        self.save = QPushButton("Create AI proposals")
        self.save.setToolTip("Create unreviewed AI proposals from the candidate patches above the display threshold")
        self.save.clicked.connect(self.saveRequested)
        self.save.setEnabled(False)
        layout.addWidget(self.save)
        self.status = QLabel("")
        self.status.setWordWrap(True)
        layout.addWidget(self.status)
        notice = QLabel("Research only — not for diagnostic use. Caption-trained patch scores; "
                        "not probabilities or segmentation boundaries. Chemical identity remains unconfirmed.")
        notice.setWordWrap(True)
        layout.addWidget(notice)
        self.hide()

    def set_running(self, running):
        for widget in (self.find, self.scope, self.device, self.size, self.stride):
            widget.setEnabled(not running)
        self.cancel.setEnabled(running)
        self.save.setEnabled(not running and bool(self.runs.currentData()))

    def set_runs(self, runs, active_id=None):
        self.runs.blockSignals(True)
        self.runs.clear()
        for run in runs:
            p = run["provenance"]
            self.runs.addItem(f"{p['run_at']} · {len(run['tiles'])} patches", p["run_id"])
        idx = self.runs.findData(active_id)
        self.runs.setCurrentIndex(idx if idx >= 0 else self.runs.count()-1)
        self.runs.blockSignals(False)
